"""Trainer-authored visible tests — restored over the learner checkout at grade time.

The tests check behaviour against the user story's acceptance criteria: which inserts and deletes
PostgreSQL accepts or rejects, and which values it stores. Any suitable design passes; the tests do
not look at constraint names, statement layout or one particular spelling of a type.
Every test gets its own new database with src/schema.sql loaded, so tests never see each other's rows.
Student inserts give explicit ids with OVERRIDING SYSTEM VALUE, so a plain whole-number id and an
identity id (GENERATED BY DEFAULT or GENERATED ALWAYS) are all accepted.
"""

from decimal import Decimal

from test.support import CHARACTERS, WHOLE_NUMBER, accepted, column_type, rejected, seed, stored_grade


def test_task1_tables(schema):
    db = schema
    for table in ("students", "courses", "enrollments"):
        found = db.execute(
            "SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = %s", (table,)).fetchone()
        assert found is not None, f"schema.sql must create a table named {table}."
    for table, column in (("students", "id"), ("students", "name"), ("students", "email"),
                          ("courses", "code"), ("courses", "title"), ("courses", "capacity"),
                          ("enrollments", "student_id"), ("enrollments", "course_code"),
                          ("enrollments", "enrolled_at"), ("enrollments", "grade")):
        column_type(db, table, column)


def test_task2_students(schema):
    db = schema
    c1 = "Criterion 1 (students):"
    assert column_type(db, "students", "id") in WHOLE_NUMBER, \
        f"{c1} a student id is a whole number, so students.id needs a whole-number type."
    assert column_type(db, "students", "name") in CHARACTERS, \
        f"{c1} students.name holds text, so it needs a character type."
    assert column_type(db, "students", "email") in CHARACTERS, \
        f"{c1} students.email holds text, so it needs a character type."
    seed(db)
    rejected(db, "INSERT INTO students (id, name, email) OVERRIDING SYSTEM VALUE VALUES (1, 'Ben Okafor', 'ben@example.com')", "23505",
             f"{c1} the id identifies one student, so a second student with id 1 must be rejected.")
    rejected(db, "INSERT INTO students (id, name, email) OVERRIDING SYSTEM VALUE VALUES (NULL, 'Ben Okafor', 'ben@example.com')", "23502",
             f"{c1} every student needs an id, so an empty id must be rejected.")
    rejected(db, "INSERT INTO students (id, name, email) OVERRIDING SYSTEM VALUE VALUES (2, NULL, 'ben@example.com')", "23502",
             f"{c1} the name is required.")
    rejected(db, "INSERT INTO students (id, name, email) OVERRIDING SYSTEM VALUE VALUES (2, 'Ben Okafor', NULL)", "23502",
             f"{c1} the email is required.")
    rejected(db, "INSERT INTO students (id, name, email) OVERRIDING SYSTEM VALUE VALUES (2, 'Ben Okafor', 'ana@example.com')", "23505",
             f"{c1} no two students share an email.")


def test_task3_courses(schema):
    db = schema
    c2 = "Criterion 2 (courses):"
    assert column_type(db, "courses", "code") in CHARACTERS, \
        f"{c2} a course code such as SQL101 holds letters and digits, so courses.code needs a character type."
    assert column_type(db, "courses", "capacity") in WHOLE_NUMBER, \
        f"{c2} capacity is a whole number, so courses.capacity needs a whole-number type."
    seed(db)
    rejected(db, "INSERT INTO courses (code, title, capacity) VALUES ('SQL101', 'Again', 10)", "23505",
             f"{c2} the code identifies one course, so a second course SQL101 must be rejected.")
    rejected(db, "INSERT INTO courses (code, title, capacity) VALUES (NULL, 'JDBC', 10)", "23502",
             f"{c2} every course needs a code.")
    rejected(db, "INSERT INTO courses (code, title, capacity) VALUES ('JDBC201', NULL, 10)", "23502",
             f"{c2} the title is required.")
    rejected(db, "INSERT INTO courses (code, title, capacity) VALUES ('JDBC201', 'JDBC', NULL)", "23502",
             f"{c2} the capacity is required.")
    rejected(db, "INSERT INTO courses (code, title, capacity) VALUES ('JDBC201', 'JDBC', 0)", "23514",
             f"{c2} capacity must be greater than 0, so 0 must be rejected.")


def test_task4_enrollment_keys(schema):
    db = schema
    c3 = "Criterion 3 (many-to-many):"
    c5 = "Criterion 5 (existing student and course):"
    seed(db)
    accepted(db, "INSERT INTO courses (code, title, capacity) VALUES ('JDBC201', 'JDBC', 20)", f"{c3} a second course.")
    accepted(db, "INSERT INTO students (id, name, email) OVERRIDING SYSTEM VALUE VALUES (2, 'Ben Okafor', 'ben@example.com')",
             f"{c3} a second student.")
    accepted(db, "INSERT INTO enrollments (student_id, course_code) VALUES (1, 'SQL101')", f"{c3} a student enrolls in a course.")
    accepted(db, "INSERT INTO enrollments (student_id, course_code) VALUES (1, 'JDBC201')",
             f"{c3} a student can enroll in many courses.")
    accepted(db, "INSERT INTO enrollments (student_id, course_code) VALUES (2, 'SQL101')", f"{c3} a course has many students.")
    rejected(db, "INSERT INTO enrollments (student_id, course_code) VALUES (1, 'SQL101')", "23505",
             f"{c3} a student cannot enroll in the same course twice.")
    rejected(db, "INSERT INTO enrollments (student_id, course_code) VALUES (9, 'SQL101')", "23503",
             f"{c5} student 9 does not exist.")
    rejected(db, "INSERT INTO enrollments (student_id, course_code) VALUES (1, 'NOPE999')", "23503",
             f"{c5} course NOPE999 does not exist.")
    rejected(db, "INSERT INTO enrollments (student_id, course_code) VALUES (NULL, 'SQL101')", "23502",
             f"{c5} an enrollment must name a student.")
